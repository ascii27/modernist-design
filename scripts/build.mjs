#!/usr/bin/env node
// Builds dist/ from project/ — no dependencies. Run: node scripts/build.mjs
// 1. compiles project/tokens.json -> project/tokens.css (same layout the artifact page writes)
// 2. writes dist/modernist.css (fonts + tokens + components), dist/tokens.json, dist/assets, dist/templates
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const P = (...p) => path.join(root, 'project', ...p);
const D = (...p) => path.join(root, 'dist', ...p);
const BLOB = '/_blob/492703acdc8340208dff9f988cb3c6e0';

const t = JSON.parse(fs.readFileSync(P('tokens.json'), 'utf8'));
const first = t.color.themes[0].id;
const val = (v) => (typeof v === 'string' ? v : v[first]);
const ref = (v) => (/^\{.+\}$/.test(v) ? `var(--${v.slice(1, -1)})` : v);

// ---- tokens.css ----
const L = [`/* ${t.name} — generated from tokens.json */`, `:root, [data-theme="${first}"] {`];
for (const c of t.color.tokens) L.push(`  --${c.name}: ${ref(val(c.value))};`);
for (const s of t.shadow?.tokens ?? []) L.push(`  --${s.name}: ${val(s.value)};`);
L.push('}');
for (const th of t.color.themes.slice(1)) {
  L.push(`[data-theme="${th.id}"] {`);
  for (const c of t.color.tokens) if (typeof c.value === 'object' && c.value[th.id]) L.push(`  --${c.name}: ${ref(c.value[th.id])};`);
  for (const s of t.shadow?.tokens ?? []) if (typeof s.value === 'object' && s.value[th.id]) L.push(`  --${s.name}: ${s.value[th.id]};`);
  L.push('}');
}
L.push(':root {');
const skip = new Set(['name', 'version', 'meta', 'color', 'type', 'shadow']);
for (const [k, fam] of Object.entries(t)) if (!skip.has(k) && fam?.tokens) for (const x of fam.tokens) L.push(`  --${x.name}: ${x.value};`);
for (const [k, v] of Object.entries(t.type.families)) L.push(`  --font-${k}: ${v};`);
L.push('}');
for (const g of t.type.groups) for (const s of g.styles) {
  let d = `font-family: var(--font-${s.family ?? g.family}); font-size: ${s.fontSize}; line-height: ${s.lineHeight}; font-weight: ${s.fontWeight};`;
  if (s.letterSpacing) d += ` letter-spacing: ${s.letterSpacing};`;
  L.push(`.${s.name} { ${d} }`);
}
const tokensCss = L.join('\n') + '\n';
fs.writeFileSync(P('tokens.css'), tokensCss);

// ---- dist ----
fs.rmSync(D(), { recursive: true, force: true });
fs.mkdirSync(D('assets'), { recursive: true });
const bundle = fs.readFileSync(P('components', 'bundle.css'), 'utf8');
const imports = bundle.match(/^@import .*;[ \t]*$/gm) ?? [];
const body = imports.reduce((s, i) => s.replace(i, ''), bundle).replace(/^\/\*.*?\*\/\s*/s, '');
fs.writeFileSync(D('modernist.css'),
  `/* Modernist — one stylesheet: fonts, tokens, components. Generated by scripts/build.mjs from project/; do not edit. */\n` +
  imports.join('\n') + '\n\n' + tokensCss.replace(/^\/\*.*?\*\/\n/, '') + '\n' + body.trimStart());
fs.copyFileSync(P('tokens.json'), D('tokens.json'));
fs.copyFileSync(P('assets', 'Photography', 'photo.jpg'), D('assets', 'photo.jpg'));
for (const tpl of fs.readdirSync(P('templates'))) {
  fs.mkdirSync(D('templates', tpl), { recursive: true });
  for (const f of fs.readdirSync(P('templates', tpl))) {
    let s = fs.readFileSync(P('templates', tpl, f), 'utf8');
    if (f === 'ds-base.js') {
      s = s.replace(/for \(const p of \[[^\]]*\]\)/, "for (const p of ['modernist.css'])")
           .replace(/\n  const s = document\.createElement\('script'\);[\s\S]*?document\.head\.appendChild\(s\);/, '');
    }
    if (f === 'index.html') s = s.split(BLOB).join('../../assets/photo.jpg');
    fs.writeFileSync(D('templates', tpl, f), s);
  }
}
console.log('built project/tokens.css and dist/');
